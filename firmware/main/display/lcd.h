#pragma once
// Экран GC9A01 через esp_lcd: инициализация и выгрузка полос кадра по DMA.
#include <cstdint>

namespace lcd {

bool init();

// Выгрузить строки [y0, y0 + h) полной ширины. rows — RGB565 big-endian (старший байт
// первым), то есть ровно в том порядке, в каком байты уходят в панель. Ждёт конца передачи.
void blit(int y0, int h, const uint8_t *rows);

// То же без ожидания: передача встаёт в очередь DMA. Буфер нельзя трогать, пока она не
// закончится, — см. wait().
void blit_async(int y0, int h, const uint8_t *rows);

// Ждать, пока в очереди останется не больше max_pending передач. Передачи заканчиваются по
// порядку, поэтому wait(1) освобождает все буферы, кроме последнего отправленного.
void wait(int max_pending);

// Сколько передач ещё в очереди, без ожидания.
int pending();

}  // namespace lcd
